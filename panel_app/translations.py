def ui(portuguese, english):
    from panel_app import runtime
    return english if runtime.LANG == "en" else portuguese

def translate(catalog, language, key, default=None):
    return catalog.get(language, {}).get(key, default or key)

def text(value, language):
    if not isinstance(value, str) or not value:
        return value
    table = PT_EN if language == "en" else EN_PT
    if value in table:
        return table[value]
    result = value
    for source in sorted(table, key=len, reverse=True):
        if source in result:
            result = result.replace(source, table[source])
    return result
